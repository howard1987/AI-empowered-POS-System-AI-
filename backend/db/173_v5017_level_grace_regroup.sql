-- V5.0.17：等级保护缓冲期设置项归位到「会员管理」并正名
--   背景：member.level_grace_days（等级降级宽限天数）历史上挂在「财务管理」分组
--        （早期分红与等级判定混在一起），但其语义是会员等级保级缓冲期，与财务无关；
--        且 V5.0.17 起语义已由「本金判级宽限」升级为「成长值保级缓冲期」，
--        原名「降级宽限」已不准确。
--   处理：归位到「会员管理」（与成长值规则同页管理），更名为「等级保护缓冲期(天)」。
--   注意：迁移执行器按分号拆句，本文件不使用 PL/pgSQL 块。
UPDATE system_settings
   SET group_name = '会员管理',
       display_name = '等级保护缓冲期(天)',
       value_type = 'number',
       remark = '近考核周期成长值不达保级线后进入缓冲期，期间保留全部会员权益；期内补足成长即退出，到期仍不达标才正式下调。默认 30 天'
 WHERE setting_key = 'member.level_grace_days';