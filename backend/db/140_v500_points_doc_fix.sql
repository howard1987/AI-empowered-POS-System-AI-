-- 140 · V5.0.1 积分抵现设置口径纠偏（仅备注/显示名，行为零变更）
--
-- 根因（老板反馈 #14「前台与后台的设置或说明有冲突」）：
--   pos.points.rate 后台文案写的是「分/百积分（本键存每百积分对应「分」）」，
--   但前后端代码实际语义是「每 1 元所需积分」（points / rate = 可抵元）——两者差 100 倍，
--   老板按文案理解换算必然对不上账。代码语义自 V4.18.3 上线即如此且两侧一致，
--   故按「改文案对齐代码」处理（不改行为、不动存量值）。
--   同时补充 pos.points.max_pct 的「0=不启用上限」说明（代码 ：696 0 即关闭上限）。
-- 幂等：UPDATE 按 setting_key 精确命中；禁改 001~139 已应用迁移。
-- ─────────────────────────────────────────────────────────────────────────────

UPDATE system_settings
   SET display_name = '积分抵现比例(每1元所需积分)',
       remark = '多少积分抵 1 元现金（如 100 = 100 积分抵 1 元）；0 = 关闭积分抵现。前台与后端均按此口径换算。'
 WHERE setting_key = 'pos.points.rate';

UPDATE system_settings
   SET remark = '单笔订单积分抵现金额不超过应收的该百分比（%）；0 或留空 = 不启用上限（可全额抵扣）'
 WHERE setting_key = 'pos.points.max_pct';
